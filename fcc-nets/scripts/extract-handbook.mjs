// Extracts the Club Handbook (public/club-handbook.html) into content
// modules for the /handbook-review page, word for word.
//
//   node scripts/extract-handbook.mjs
//
// Writes:
//   src/handbook-review/content/generated/parts.js     13 parts: anchor, eyebrow, title, toc title/summary, html, word count;
//                                                      plus FABRIC: the intro's "The fabric of FCC" block (read-only, no verdict)
//   src/handbook-review/content/generated/handbook.css the handbook's own CSS, scoped (tokens → .hbr, rules → .hb-doc)
//   public/handbook-review/crest.webp                  the crest embedded in the handbook hero
//
// Updating the handbook (e.g. v0.4) is a content-only change: replace
// club-handbook.html, re-run this script, bump HANDBOOK_VERSION in
// src/handbook-review/content/config.js if needed. No logic edits.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(resolve(root, "public/club-handbook.html"), "utf8");

const outDir = resolve(root, "src/handbook-review/content/generated");
mkdirSync(outDir, { recursive: true });
mkdirSync(resolve(root, "public/handbook-review"), { recursive: true });

const decode = (s) => s
  .replace(/<[^>]+>/g, "")
  .replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, " ")
  .replace(/\s+/g, " ").trim();

// ── Crest ────────────────────────────────────────────────────
const crest = src.match(/<img class="crest" src="data:image\/webp;base64,([^"]+)"/);
if (!crest) throw new Error("crest image not found");
writeFileSync(resolve(root, "public/handbook-review/crest.webp"), Buffer.from(crest[1], "base64"));

// ── Version line ─────────────────────────────────────────────
const heroSub = decode(src.match(/<p class="hero-sub">([\s\S]*?)<\/p>/)[1]);
const footer = [...src.match(/<footer>([\s\S]*?)<\/footer>/)[1].matchAll(/<span>([\s\S]*?)<\/span>/g)].map((m) => decode(m[1]));

// ── Table of contents (titles + one-line summaries) ─────────
const toc = {};
for (const m of src.matchAll(/<a href="#([a-z0-9-]+)"><span class="n">(\d+)<\/span><span><span class="t">([\s\S]*?)<\/span><br><span class="s">([\s\S]*?)<\/span><\/span><\/a>/g)) {
  toc[m[1]] = { n: Number(m[2]), title: decode(m[3]), summary: decode(m[4]) };
}

// ── Parts ────────────────────────────────────────────────────
const parts = [];
for (const m of src.matchAll(/<section id="([a-z0-9-]+)"(?:[^>]*)>([\s\S]*?)\n  <\/section>/g)) {
  const [, anchor, inner] = m;
  if (anchor === "intro") continue;
  const head = inner.match(/<p class="eyebrow">([\s\S]*?)<\/p><h2>([\s\S]*?)<\/h2>/);
  if (!head) throw new Error(`no sec-head in #${anchor}`);
  const t = toc[anchor];
  if (!t) throw new Error(`#${anchor} missing from the table of contents`);
  const html = inner.replace(/^\n/, "").replace(/\s+$/, "");
  parts.push({
    id: t.n,
    anchor,
    eyebrow: decode(head[1]),
    heading: decode(head[2]),
    tocTitle: t.title,
    summary: t.summary,
    words: decode(html).split(" ").length,
    html,
  });
}
parts.sort((a, b) => a.id - b.id);
if (parts.length !== 13 || parts.some((p, i) => p.id !== i + 1)) {
  throw new Error(`expected parts 1–13, got ${parts.map((p) => p.id).join(",")}`);
}

// ── "The fabric of FCC" (inside the intro, not a part) ──────
// The whole <div class="role" id="fabric"> block, found by matching its
// closing </div>. Optional: null if a future version drops it.
let fabric = null;
const fabricStart = src.indexOf('<div class="role" id="fabric">');
if (fabricStart !== -1) {
  const tag = /<\/?div\b[^>]*>/g;
  tag.lastIndex = fabricStart;
  let depth = 0, end = -1, m;
  while ((m = tag.exec(src))) {
    depth += m[0].startsWith("</") ? -1 : 1;
    if (depth === 0) { end = tag.lastIndex; break; }
  }
  if (end === -1) throw new Error("#fabric block is not closed");
  const html = src.slice(fabricStart, end);
  const head = html.match(/<h3>([\s\S]*?)<\/h3>/);
  const tags = [...(html.match(/<div class="tags">([\s\S]*?)<\/div>/)?.[1] || "").matchAll(/<span>([\s\S]*?)<\/span>/g)].map((t) => decode(t[1]));
  fabric = { anchor: "fabric", title: decode(head ? head[1] : "The fabric of FCC"), tags, words: decode(html).split(" ").length, html };
}

writeFileSync(resolve(outDir, "parts.js"),
  "// GENERATED by scripts/extract-handbook.mjs from public/club-handbook.html. Do not edit by hand.\n" +
  `export const SOURCE_VERSION_LINE = ${JSON.stringify(heroSub)};\n` +
  `export const SOURCE_FOOTER = ${JSON.stringify(footer)};\n` +
  `export const PARTS = ${JSON.stringify(parts, null, 2)};\n` +
  `export const FABRIC = ${JSON.stringify(fabric, null, 2)};\n`);

// ── CSS, scoped ──────────────────────────────────────────────
// Tokens (:root) move to .hbr (the page root, which also carries
// data-theme). Element/class rules are prefixed with .hb-doc so nothing
// leaks outside the ported content. Rules for the static page's own
// chrome (hero, sticky nav, contents grid, footer) are dropped.
const css = src.match(/<style>([\s\S]*?)<\/style>/)[1].replace(/\/\*[\s\S]*?\*\//g, "");
const SKIP = /^(html|body|a|\*|:focus-visible|\.hero|\.crest|\.badge|\.motto|\.bars|\.nav|\.wrap|\.toc|footer|section:not\(#intro\)::before)/;

function scopeSelector(sel) {
  sel = sel.trim();
  if (sel.startsWith(":root")) return sel.replace(/^:root/, ".hbr");
  if (SKIP.test(sel)) return null;
  sel = sel.replace(/section:not\(#intro\)/g, "section");
  return `.hb-doc ${sel}`;
}

function scopeRules(block) {
  let out = "";
  let i = 0;
  while (i < block.length) {
    const open = block.indexOf("{", i);
    if (open === -1) break;
    const prelude = block.slice(i, open).trim();
    // find matching close brace
    let depth = 1, j = open + 1;
    while (j < block.length && depth) { if (block[j] === "{") depth++; else if (block[j] === "}") depth--; j++; }
    const body = block.slice(open + 1, j - 1);
    if (prelude.startsWith("@media")) {
      const innerScoped = scopeRules(body);
      if (innerScoped.trim()) out += `${prelude}{\n${innerScoped}}\n`;
    } else {
      const sels = prelude.split(",").map(scopeSelector).filter(Boolean);
      if (sels.length) out += `${sels.join(",")}{${body.trim()}}\n`;
    }
    i = j;
  }
  return out;
}

writeFileSync(resolve(outDir, "handbook.css"),
  "/* GENERATED by scripts/extract-handbook.mjs from public/club-handbook.html. Do not edit by hand. */\n" + scopeRules(css));

console.log(`Extracted ${parts.length} parts (${parts.reduce((n, p) => n + p.words, 0)} words)${fabric ? ` + "${fabric.title}" (${fabric.words} words)` : ""} · ${heroSub}`);
